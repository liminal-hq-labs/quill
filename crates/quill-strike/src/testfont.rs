/// A bitmap of grey levels, rows of columns, each 0 to 3.
type Levels = Vec<Vec<u8>>;

fn scaled(rows: &[u8; 7], g: usize) -> Levels {
	let mut out = Vec::new();
	for r in rows {
		let line: Vec<u8> = (0..5 * g)
			.map(|x| u8::from((r >> (4 - x / g)) & 1 != 0) * 3)
			.collect();
		for _ in 0..g {
			out.push(line.clone());
		}
	}
	out
}

/// Widens a bitmap by `by` columns on the right and runs `f` over (row, column) to fill the new bitmap from the old.
fn widen(l: &Levels, by: usize, f: impl Fn(&Levels, usize, usize) -> u8) -> Levels {
	let w = l.first().map_or(0, Vec::len) + by;
	(0..l.len())
		.map(|y| (0..w).map(|x| f(l, y, x)).collect())
		.collect()
}

fn at(l: &Levels, y: usize, x: isize) -> u8 {
	if x < 0 {
		return 0;
	}
	l.get(y)
		.and_then(|r| r.get(x as usize))
		.copied()
		.unwrap_or(0)
}

fn bold(l: &Levels) -> Levels {
	widen(l, 1, |l, y, x| {
		at(l, y, x as isize).max(at(l, y, x as isize - 1))
	})
}

fn italic(l: &Levels) -> Levels {
	let h = l.len();
	let shear = |y: usize| (h - 1 - y) / 3;
	let by = shear(0);
	widen(l, by, |l, y, x| at(l, y, x as isize - shear(y) as isize))
}

/// Feet on the serif face: the bottom row is drawn a pixel wider each side.
fn serif(l: &Levels) -> Levels {
	let h = l.len();
	let wide = widen(l, 2, |l, y, x| at(l, y, x as isize - 1));
	widen(&wide, 0, |l, y, x| {
		if y + 1 == h {
			at(l, y, x as isize)
				.max(at(l, y, x as isize - 1))
				.max(at(l, y, x as isize + 1))
		} else {
			at(l, y, x as isize)
		}
	})
}

/// Rounds a 1-bit bitmap into four grey levels: ink with two or more inked neighbours is full, a lone one is half, and paper beside
/// three or more is a quarter.
fn smooth(l: &Levels) -> Levels {
	let h = l.len() as isize;
	let w = l.first().map_or(0, Vec::len) as isize;
	(0..h)
		.map(|y| {
			(0..w)
				.map(|x| {
					let on = |dy: isize, dx: isize| {
						u8::from(at(l, (y + dy).max(0) as usize, x + dx) > 0 && y + dy >= 0)
					};
					let k = on(-1, 0) + on(1, 0) + on(0, -1) + on(0, 1);
					match (on(0, 0), k) {
						(1, 2..) => 3,
						(1, _) => 2,
						(0, 3..) => 1,
						_ => 0,
					}
				})
				.collect()
		})
		.collect()
}

fn pack(l: &Levels, bpp: u8) -> Vec<u8> {
	let w = l.first().map_or(0, Vec::len);
	let stride = (w * usize::from(bpp)).div_ceil(8);
	let mut out = Vec::new();
	for row in l {
		let mut bytes = std::vec![0u8; stride];
		for (x, v) in row.iter().enumerate() {
			if bpp == 1 {
				bytes[x / 8] |= u8::from(*v > 0) << (7 - x % 8);
			} else {
				bytes[x / 4] |= (v & 3) << (6 - 2 * (x % 4));
			}
		}
		out.extend_from_slice(&bytes);
	}
	out
}

fn strike(face: u8, style: u8, g: usize, mono: bool, seriffed: bool) -> StrikeSpec {
	let bpp = if g == 2 && !mono { 2 } else { 1 };
	let mut advances = [6 * g as u8; GLYPHS];
	let mut glyphs = Vec::new();
	advances[0] = 3 * g as u8;
	for (ch, rows) in SHAPES {
		let mut l = scaled(rows, g);
		if seriffed {
			l = serif(&l);
		}
		if style & 1 != 0 {
			l = bold(&l);
		}
		if style & 2 != 0 {
			l = italic(&l);
		}
		if bpp == 2 {
			l = smooth(&l);
		}
		let cols: Vec<usize> = (0..l.first().map_or(0, Vec::len))
			.filter(|x| l.iter().any(|r| r[*x] > 0))
			.collect();
		let (Some(&lo), Some(&hi)) = (cols.first(), cols.last()) else {
			continue;
		};
		let rows_used: Vec<usize> = (0..l.len())
			.filter(|y| l[*y].iter().any(|v| *v > 0))
			.collect();
		let (top_row, bottom_row) = (rows_used[0], rows_used[rows_used.len() - 1]);
		let cropped: Levels = l[top_row..=bottom_row]
			.iter()
			.map(|r| r[lo..=hi].to_vec())
			.collect();
		let w = hi - lo + 1;
		let base = 7 * g;
		let adv = if mono {
			6 * g
		} else {
			w + g + usize::from(style & 1 != 0)
		};
		let left = if mono { adv.saturating_sub(w) / 2 } else { 0 };
		advances[usize::from(ch - 0x20)] = adv as u8;
		glyphs.push((
			*ch,
			GlyphSpec {
				left: left as i8,
				top: (base - top_row) as i8,
				width: w as u8,
				height: cropped.len() as u8,
				bits: pack(&cropped, bpp),
			},
		));
	}
	if !mono {
		advances[0] = 3 * g as u8;
	}
	StrikeSpec {
		face,
		style,
		size: if g == 1 { 18 } else { 36 },
		pixels: 12 * g as u8,
		ascent: 8 * g as u8,
		descent: 2 * g as u8,
		leading: g as u8,
		bpp,
		advances,
		glyphs,
	}
}

/// The bytes of the test font: a serif, a swiss and a modern face in four styles at 12 and 24 pixels (9 and 18 point), 24 strikes.
/// Faces 0 and 1 are 2-bit at 24 pixels; everything else is 1-bit.
pub fn test_font() -> Vec<u8> {
	let mut strikes = Vec::new();
	for face in 0..3u8 {
		for style in 0..4u8 {
			for g in [1usize, 2] {
				strikes.push(strike(face, style, g, face == 2, face == 0));
			}
		}
	}
	build(&strikes)
}
