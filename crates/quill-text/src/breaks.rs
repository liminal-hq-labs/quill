/// Whether a line may break between a character of class `before` and one of class `after`.
pub fn break_between(before: Brk, after: Brk) -> bool {
	match (before, after) {
		// Nothing breaks before a space or closing punctuation.
		(_, Brk::Space | Brk::Close) => false,
		// A hyphen or dash stays with what it follows, after a space aside.
		(_, Brk::After) => before == Brk::Space,
		// A no-break space or joiner stays put, after a space or a hyphen aside.
		(_, Brk::Glue) => matches!(before, Brk::Space | Brk::After),
		(Brk::Glue | Brk::Open, _) => false,
		(Brk::Space | Brk::After, _) => true,
		_ => before == Brk::Ideo || after == Brk::Ideo,
	}
}

/// Whether a line may break between `before` and `after`, two neighbouring characters.
pub fn can_break(before: char, after: char) -> bool {
	break_between(brk(before), brk(after))
}
