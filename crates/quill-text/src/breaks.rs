//! Seven classes folded from `LineBreak.txt`, and one rule over a pair of them. A line may break after a space, after
//! U+200B, after a hyphen or dash, and before and after a CJK ideograph, kana or Hangul syllable, except before closing
//! punctuation and after opening punctuation; never at a no-break space, before a space, inside a cluster (the caller
//! checks that with [`cluster`](crate::cluster)) or in the middle of a run of letters.
//!
//! Where it differs from UAX #14, and why: a break after closing punctuation, a break between numbers and the quotes,
//! the rule that opening punctuation keeps a space after it with it, and a break before a word joiner after a space are
//! all left out; they matter to scripts and typesetting the v1 build does not do. `LineBreakTest.txt` is checked on the
//! lines made only of the classes the rule answers exactly (see `tests/ucd/LineBreakTest.txt`).

use crate::unitab::{lookup, pack as r, Seq};

/// A character's part in line breaking.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Brk {
	/// Anything else: a letter, a digit, a symbol. Joins its neighbours.
	Other = 0,
	/// A space (SP) or U+200B (ZW): no break before it, a break after the run of them.
	Space = 1,
	/// A hyphen or dash (HY, BA, B2): no break before it, a break after it.
	After = 2,
	/// An ideograph, kana or Hangul syllable (ID, CJ, H2, H3, JL, JV, JT): a break before and after.
	Ideo = 3,
	/// Closing punctuation (CL, CP, NS, EX, IS): no break before it.
	Close = 4,
	/// Opening punctuation (OP): no break after it.
	Open = 5,
	/// A no-break space or a joiner (GL, WJ, ZWJ): no break either side, except after a space or a hyphen.
	Glue = 6,
}

impl Brk {
	pub(crate) fn from_u8(value: u8) -> Brk {
		match value {
			1 => Brk::Space,
			2 => Brk::After,
			3 => Brk::Ideo,
			4 => Brk::Close,
			5 => Brk::Open,
			6 => Brk::Glue,
			_ => Brk::Other,
		}
	}
}

