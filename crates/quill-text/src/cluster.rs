//! A cluster is a base character followed by any number of combining marks, variation selectors, emoji modifiers and
//! tags, a ZWJ with the pictographic after it, or a pair of regional indicators. This is UAX #29's extended grapheme
//! cluster without the rules for Hangul jamo, Prepend characters and Indic conjuncts, which only the later scripts need.
//! The table is generated from `GraphemeBreakProperty.txt` and `emoji-data.txt`.
//!
//! [`joins`] takes two neighbours, so it cannot look behind a ZWJ: a ZWJ joins any pictographic after it, where UAX #29
//! needs a pictographic before the ZWJ too. A caller walking a string keeps a count of the regional indicators it has
//! seen in a row and passes whether that count is odd.

use crate::unitab::{lookup, pack as r, Seq};

/// What a character does to the cluster around it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Class {
	/// Anything else: it starts a cluster.
	Other = 0,
	/// A combining mark (Mn and Me, and a spacing mark of a script drawn in v1), a variation selector, an emoji modifier,
	/// a tag character or U+200C: it joins the character before.
	Extend = 1,
	/// U+200D ZERO WIDTH JOINER.
	Zwj = 2,
	/// A regional indicator, U+1F1E6 to U+1F1FF.
	Regional = 3,
	/// Extended_Pictographic, an emoji or a symbol that has one.
	Pictographic = 4,
	/// CR, LF and the control and format characters: never joined, and nothing joins to them.
	Control = 5,
}

impl Class {
	pub(crate) fn from_u8(value: u8) -> Class {
		match value {
			1 => Class::Extend,
			2 => Class::Zwj,
			3 => Class::Regional,
			4 => Class::Pictographic,
			5 => Class::Control,
			_ => Class::Other,
		}
	}
}

