/// The cluster class of `c`.
pub fn class(c: char) -> Class {
	class_in(Seq::Words(&RANGES), u32::from(c))
}

/// Whether `c` joins the cluster before it on its own: a combining mark, a variation selector, an emoji modifier, a tag.
pub fn is_extend(c: char) -> bool {
	class(c) == Class::Extend
}

/// Whether `c` is a regional indicator.
pub fn is_regional(c: char) -> bool {
	class(c) == Class::Regional
}

/// Whether `c` is Extended_Pictographic.
pub fn is_pictographic(c: char) -> bool {
	class(c) == Class::Pictographic
}

/// Whether `next` is in the same cluster as `prev`, the character just before it. `regional_odd` is whether an odd
/// number of regional indicators come in a row up to and including `prev`: a flag is a pair, so a third starts a new one.
pub fn joins(prev: char, next: char, regional_odd: bool) -> bool {
	let (before, after) = (class(prev), class(next));
	if before == Class::Control || after == Class::Control {
		return false;
	}
	match (before, after) {
		(_, Class::Extend | Class::Zwj) => true,
		(Class::Zwj, Class::Pictographic) => true,
		(Class::Regional, Class::Regional) => regional_odd,
		_ => false,
	}
}
