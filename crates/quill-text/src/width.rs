pub(crate) fn is_wide_in(table: Seq<'_>, cp: u32) -> bool {
	lookup(table, cp) != 0
}

/// Whether `c` is East Asian Wide or Fullwidth.
pub fn is_wide(c: char) -> bool {
	is_wide_in(Seq::Words(&RANGES), u32::from(c))
}
