//! A character is a letter when its General Category is L, M or Nd (so `é`, `ж`, `ß` and a combining mark are inside a
//! word), punctuation for P and S, a space for Z and the white space controls, and each CJK ideograph, kana or Hangul
//! syllable is [`Class::Ideo`]: a caller makes each ideograph a word of its own and a run of kana or Hangul one.
//! Control, format (except U+200C and U+200D, which are letters so a word is not cut at one), unassigned, private-use
//! and surrogate code points are [`Class::Punct`]; the table does not tell the last three from their neighbours, which
//! is why it is small.

use crate::unitab::{lookup, pack as r, Seq};

/// A character's part in a word.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Class {
	/// Punctuation, symbols and everything that is not in a word.
	Punct = 0,
	/// A letter, a mark or a decimal digit.
	Letter = 1,
	/// A space or a white space control.
	Space = 2,
	/// An ideograph, a kana or a Hangul syllable.
	Ideo = 3,
}

impl Class {
	pub(crate) fn from_u8(value: u8) -> Class {
		match value {
			1 => Class::Letter,
			2 => Class::Space,
			3 => Class::Ideo,
			_ => Class::Punct,
		}
	}
}

