"""Run as `python3 -I scripts/gen-codepages.py` to rewrite the three outputs, or with `--check` to fail when one is out of date.

Outputs:
  crates/quill-text/src/cpdata.rs            the tables, as `u16` for the bytes 0x80 to 0xFF of each page
  assets/codepages/CPAGES.BIN                the same, little-endian, as the Win16 build's RCDATA resource (resource 100)
  crates/quill-text/tests/data/codepages.tsv the golden: `page<TAB>byte<TAB>code point`, one line per entry

The pages and their order are the order of `quill_text::codepage::CodePage`. A byte the code page leaves undefined maps to the C1
control of the same number when it is 0x80 to 0x9F (so every byte round-trips, as `cp1252` does) and to U+FFFD above that.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = [1250, 1251, 1252, 1253, 1254, 1257]


def table(page):
	out = []
	for b in range(0x80, 0x100):
		try:
			out.append(ord(bytes([b]).decode("cp%d" % page)))
		except UnicodeDecodeError:
			out.append(b if b < 0xA0 else 0xFFFD)
	return out


def rust():
	s = "// Windows code page tables 1250, 1251, 1252, 1253, 1254 and 1257 for the bytes 0x80 to 0xFF. Generated by scripts/gen-codepages.py.\n"
	s += "//\n// (c) Copyright 2026 Liminal HQ, Scott Morris\n// SPDX-License-Identifier: Apache-2.0 OR MIT\n\n"
	s += "/// One row per page, in the order of `CodePage`; each holds the Unicode code point of the bytes 0x80 to 0xFF.\n"
	s += "#[rustfmt::skip]\npub(crate) const HIGH: [[u16; 128]; %d] = [\n" % len(PAGES)
	for p in PAGES:
		s += "\t// %d\n\t[\n" % p
		t = table(p)
		for i in range(0, 128, 8):
			s += "\t\t" + ", ".join("0x%04X" % v for v in t[i : i + 8]) + ",\n"
		s += "\t],\n"
	return (s + "];\n").encode()


def blob():
	out = bytearray()
	for p in PAGES:
		for v in table(p):
			out += v.to_bytes(2, "little")
	return bytes(out)


def golden():
	lines = ["# Windows code pages 0x80 to 0xFF from Python's codecs: page, byte, code point. Generated by scripts/gen-codepages.py."]
	for p in PAGES:
		for i, v in enumerate(table(p)):
			lines.append("%d\t%02X\t%04X" % (p, 0x80 + i, v))
	return ("\n".join(lines) + "\n").encode()


OUT = {
	"crates/quill-text/src/cpdata.rs": rust,
	"assets/codepages/CPAGES.BIN": blob,
	"crates/quill-text/tests/data/codepages.tsv": golden,
}

bad = False
for rel, make in OUT.items():
	path = os.path.join(ROOT, rel)
	data = make()
	if "--check" in sys.argv:
		if not os.path.exists(path) or open(path, "rb").read() != data:
			print("out of date:", rel)
			bad = True
	else:
		with open(path, "wb") as f:
			f.write(data)
sys.exit(1 if bad else 0)
