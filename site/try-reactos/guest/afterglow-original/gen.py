import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)

import numpy as np  # noqa: E402

from agart import all_art  # noqa: E402
from agdraw import DUSK, P, encode_bmp, ini_colour, mix  # noqa: E402

COLOUR_NAME = "Dusk"
SIZE_NAME = "Normal"
INI_RES = "DUSK_NORMAL_INI"
DOC = {
	"DisplayName": "Afterglow",
	"ToolTip": "Dusk captions, a near-black taskbar and a gold Start button over classic cream controls",
	"Company": "Liminal HQ",
	"Author": "Liminal HQ, Scott Morris",
	"Copyright": "(c) Copyright 2026 Liminal HQ, Scott Morris. Apache-2.0 OR MIT",
	"URL": "",
	"Version": "1.0",
	"Description": "Original Afterglow visual style for ReactOS, drawn from the Liminal HQ Afterglow palette",
}


def tokens():
	t = {k: ini_colour(v) for k, v in P.items()}
	for i, c in enumerate(DUSK):
		t[f"dusk{i + 1}"] = ini_colour(c)
	t["tab_edge"] = ini_colour(mix(DUSK[0], P["edge"], 0.6))
	return t


def res_name(path):
	return re.sub(r"[\\/.]", "_", path).upper()


def main():
	out = sys.argv[1]
	preview = sys.argv[3] if len(sys.argv) > 3 and sys.argv[2] == "--preview" else None
	art = all_art()
	os.makedirs(os.path.join(out, "textfiles"), exist_ok=True)
	total = 0
	for path, a in art.items():
		p = os.path.join(out, "art", path)
		os.makedirs(os.path.dirname(p), exist_ok=True)
		data = encode_bmp(a)
		total += len(data)
		with open(p, "wb") as f:
			f.write(data)

	# INI: substitute palette tokens, check that every image it names was drawn and every drawn image is used.
	src = open(os.path.join(here, "ini", "dusk-normal.ini"), encoding="utf-8").read()
	# Comments are dropped from the shipped copy (the engine skips them anyway) to keep the resource small.
	src = "\n".join(ln.rstrip() for ln in src.splitlines() if ln.strip() and not ln.lstrip().startswith(";"))
	tok = tokens()
	missing = sorted(set(re.findall(r"\{(\w+)\}", src)) - set(tok))
	if missing:
		sys.exit(f"unknown colour tokens: {missing}")
	ini = re.sub(r"\{(\w+)\}", lambda m: tok[m.group(1)], src)
	named = set(re.findall(r"^\s*(?:Glyph)?ImageFile\s*=\s*(\S+)", ini, re.M | re.I))
	if named - set(art):
		sys.exit(f"INI names images that were not drawn: {sorted(named - set(art))}")
	if set(art) - named:
		sys.exit(f"images drawn but not used: {sorted(set(art) - named)}")
	body = "\r\n" + ini.replace("\n", "\r\n") + "\r\n"
	with open(os.path.join(out, "textfiles", "dusk-normal.ini"), "w", encoding="utf-16-le", newline="") as f:
		f.write(body)
	themes = "\r\n[Documentation]\r\n" + "".join(f"{k} = {v}\r\n" for k, v in DOC.items())
	with open(os.path.join(out, "textfiles", "themes.ini"), "w", encoding="utf-16-le", newline="") as f:
		f.write(themes)

	def s(v):
		return v.replace('"', '""')

	rc = [
		"// Generated by gen.py. (c) Copyright 2026 Liminal HQ, Scott Morris. SPDX-License-Identifier: Apache-2.0 OR MIT",
		"LANGUAGE 0, 0",
		"1 PACKTHEM_VERSION { 0x0003 }",
		f'1 COLORNAMES {{ L"{COLOUR_NAME}\\0\\0" }}',
		f'1 SIZENAMES {{ L"{SIZE_NAME}\\0\\0" }}',
		f'1 FILERESNAMES {{ L"{INI_RES}\\0\\0" }}',
		'THEMES_INI TEXTFILE "textfiles/themes.ini"',
		f'{INI_RES} TEXTFILE "textfiles/dusk-normal.ini"',
	]
	rc += [f'{res_name(p)} BITMAP "art/{p}"' for p in sorted(art)]
	keys = list(DOC)
	rc += [
		f'STRINGTABLE {{ 1000, "{COLOUR_NAME}" }}',
		f'STRINGTABLE {{ 2000, "{COLOUR_NAME}" }}',
		f'STRINGTABLE {{ 3000, "{SIZE_NAME}" }}',
		f'STRINGTABLE {{ 4000, "{SIZE_NAME}" }}',
		"STRINGTABLE {\n" + "\n".join(f' {5000 + i}, "{s(DOC[k])}"' for i, k in enumerate(keys) if DOC[k]) + "\n}",
		"1 VERSIONINFO",
		"FILEVERSION 1,0,0,0",
		"PRODUCTVERSION 1,0,0,0",
		"FILEOS 0x40004",
		"FILETYPE 2",
		"{",
		' BLOCK "StringFileInfo" { BLOCK "040904b0" { VALUE "FileDescription", "Afterglow visual style\\0" VALUE "CompanyName", "Liminal HQ\\0" VALUE "LegalCopyright", "(c) 2026 Liminal HQ, Scott Morris. Apache-2.0 OR MIT\\0" VALUE "OriginalFilename", "afterglow.msstyles\\0" VALUE "FileVersion", "1.0\\0" } }',
		' BLOCK "VarFileInfo" { VALUE "Translation", 0x0409, 0x04b0 }',
		"}",
	]
	with open(os.path.join(out, "afterglow.rc"), "w", encoding="utf-8") as f:
		f.write("\n".join(rc) + "\n")
	print(f"{len(art)} bitmaps, {total} bytes of BMP; INI {len(body) * 2} bytes")

	if preview:  # contact sheet of every bitmap at 3x, key colour shown as a check pattern
		from PIL import Image

		tiles = []
		for path, a in art.items():
			a = np.clip(np.round(a), 0, 255).astype(np.uint8)
			k = np.all(a == [255, 0, 255], axis=2)
			yy, xx = np.indices(k.shape)
			a[k] = np.where((((yy // 2) + (xx // 2)) % 2 == 0)[k, None], [70, 70, 80], [50, 50, 58])
			tiles.append(Image.fromarray(a).resize((a.shape[1] * 3, a.shape[0] * 3), Image.NEAREST))
		W = 1400
		x = y = rowh = 0
		pos = []
		for t in tiles:
			if x + t.width > W:
				x, y, rowh = 0, y + rowh + 8, 0
			pos.append((x, y))
			x += t.width + 8
			rowh = max(rowh, t.height)
		sheet = Image.new("RGB", (W, y + rowh), (128, 128, 128))
		for t, p in zip(tiles, pos):
			sheet.paste(t, p)
		sheet.save(preview)


if __name__ == "__main__":
	main()
