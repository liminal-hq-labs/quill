#!/usr/bin/env python3
# Generate the sources of the original Afterglow visual style: bitmaps (drawn by agart.py), the Dusk / Normal INI (from
# ini/dusk-normal.ini), themes.ini and the resource script. Nothing is read from any other visual style.
# Usage: gen.py OUT_DIR [--preview PNG]   (OUT_DIR receives art/, textfiles/ and afterglow.rc)
#
