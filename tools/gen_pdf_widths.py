"""Run as `python3 -I tools/gen_pdf_widths.py [FONT_DIR] > crates/quill-pdf/src/widths.rs` with fontTools installed.

The widths of Helvetica, Times and Courier are Adobe's, and the URW base 35 fonts (Nimbus Sans, Nimbus Roman, Nimbus Mono) are
drawn to the same advances so a document set in one prints the same in the other. FONT_DIR defaults to `/usr/share/fonts/gsfonts`.
The script reads the advances from those files and checks a few against Adobe's published figures, so a wrong font fails loudly.

Windows-1252 bytes the encoding leaves unused (0x7F, 0x81, 0x8D, 0x8F, 0x90, 0x9D) take the bullet's width, which is what a PDF viewer
draws for them in WinAnsiEncoding. Bytes 0xA0 and 0xAD are the space and the hyphen.
"""

import sys

from fontTools.ttLib import TTFont

DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/gsfonts"
FACES = [
	("HELVETICA", "NimbusSans-Regular.otf"),
	("HELVETICA_BOLD", "NimbusSans-Bold.otf"),
	("TIMES", "NimbusRoman-Regular.otf"),
	("TIMES_BOLD", "NimbusRoman-Bold.otf"),
	("TIMES_ITALIC", "NimbusRoman-Italic.otf"),
	("TIMES_BOLD_ITALIC", "NimbusRoman-BoldItalic.otf"),
]
# Adobe's published widths for a few characters, as a guard on the source fonts.
CHECK = {
	"HELVETICA": {" ": 278, "A": 667, "a": 556, "W": 944, "i": 222},
	"HELVETICA_BOLD": {" ": 278, "A": 722, "a": 556, "W": 944, "i": 278},
	"TIMES": {" ": 250, "A": 722, "a": 444, "W": 944, "i": 278},
	"TIMES_BOLD": {" ": 250, "A": 722, "a": 500, "W": 1000, "i": 278},
	"TIMES_ITALIC": {" ": 250, "A": 611, "a": 500, "W": 833, "i": 278},
	"TIMES_BOLD_ITALIC": {" ": 250, "A": 667, "a": 500, "W": 889, "i": 278},
}


def widths(path):
	font = TTFont(path)
	cmap = font.getBestCmap()
	hmtx = font["hmtx"]
	scale = 1000 / font["head"].unitsPerEm

	def adv(code_point):
		return round(hmtx[cmap[code_point]][0] * scale)

	out = []
	for byte in range(32, 256):
		if byte == 0xA0:
			code_point = 0x20
		elif byte == 0x7F:
			code_point = 0x2022
		elif byte == 0xAD:
			code_point = 0x2D
		else:
			try:
				code_point = ord(bytes([byte]).decode("cp1252"))
			except UnicodeDecodeError:
				code_point = 0x2022
		out.append(adv(code_point))
	return out


print("// The advance widths of the standard 14 text fonts for Windows-1252 bytes 32 to 255, in thousandths of an em. Generated by")
print("// `tools/gen_pdf_widths.py` from the URW base 35 fonts, which are drawn to Adobe's advances; do not edit by hand.")
print("//")
print("// (c) Copyright 2026 Liminal HQ, Scott Morris")
print("// SPDX-License-Identifier: Apache-2.0 OR MIT")
print()
print("/// The first byte a table covers.")
print("pub const FIRST: u8 = 32;")
for name, file in FACES:
	table = widths(f"{DIR}/{file}")
	for ch, want in CHECK[name].items():
		got = table[ord(ch) - 32]
		if got != want:
			sys.exit(f"{name}: width of {ch!r} is {got}, Adobe's is {want}")
	print()
	print("#[rustfmt::skip]")
	print(f"pub const {name}: [u16; 224] = [")
	for i in range(0, 224, 16):
		print("\t" + ", ".join(str(w) for w in table[i : i + 16]) + ",")
	print("];")
