#!/usr/bin/env bash
# Stages the Windows App SDK runtime beside a Reactor exe from a Linux host: download, verify, unzip, copy, write the manifest.
#
# (c) Copyright 2026 Liminal HQ, Scott Morris
# SPDX-License-Identifier: Apache-2.0 OR MIT
#
# Follows what `windows-reactor-setup` does on Windows, without `curl.exe` or `tar.exe`. The package version and its SHA-256
# are pinned in this directory (`runtime.sha256`); `runtime.txt` is the list of runtime files Reactor copies.
#
# Usage: stage-runtime.sh [STAGE_DIR]
#   STAGE_DIR  where the runtime files and app.manifest go (default: $CACHE/stage-x64)
# Environment: QUILL_WINUI_CACHE overrides the cache (default: ${XDG_CACHE_HOME:-~/.cache}/quill-winui).
# Prints the stage directory on its last line.

set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
version="2.4.0"
package="Microsoft.WindowsAppSDK.Runtime"
nupkg_name="${package}.${version}.nupkg"
cache="${QUILL_WINUI_CACHE:-${XDG_CACHE_HOME:-$HOME/.cache}/quill-winui}"
stage="${1:-$cache/stage-x64}"
msix_in_nupkg="tools/MSIX/win10-x64/Microsoft.WindowsAppRuntime.2.msix"

for tool in curl unzip sha256sum python3; do
	command -v "$tool" >/dev/null || { echo "stage-runtime: $tool is required" >&2; exit 1; }
done

mkdir -p "$cache"

# 1. Download once, then check the pinned SHA-256 every run.
if [ ! -f "$cache/$nupkg_name" ]; then
	echo "stage-runtime: downloading $package $version from nuget.org" >&2
	curl --fail --silent --show-error --location --retry 3 --output "$cache/$nupkg_name.part" \
		"https://www.nuget.org/api/v2/package/$package/$version"
	mv "$cache/$nupkg_name.part" "$cache/$nupkg_name"
fi
(cd "$cache" && sha256sum --check --quiet "$here/runtime.sha256") || {
	echo "stage-runtime: $nupkg_name does not match tools/runtime.sha256; delete it from $cache to download again" >&2
	exit 1
}

# 2. Unzip the nupkg's x64 MSIX, then the MSIX (both are zip files).
msix_dir="$cache/msix-x64-$version"
if [ ! -f "$msix_dir/Microsoft.WindowsAppRuntime.dll" ] && [ ! -f "$msix_dir/Microsoft.ui.xaml.dll" ]; then
	rm -rf "$msix_dir" "$cache/msix-x64-$version.partial"
	mkdir -p "$cache/msix-x64-$version.partial"
	unzip -p "$cache/$nupkg_name" "$msix_in_nupkg" >"$cache/msix-x64-$version.msix"
	unzip -q "$cache/msix-x64-$version.msix" -d "$cache/msix-x64-$version.partial"
	mv "$cache/msix-x64-$version.partial" "$msix_dir"
	rm -f "$cache/msix-x64-$version.msix"
fi

# 3. Copy the files and folders runtime.txt names, matching names without regard to case.
rm -rf "$stage"
mkdir -p "$stage"
python3 -I - "$msix_dir" "$stage" "$here/runtime.txt" <<'PY'
import os, shutil, sys
src, dst, listing = sys.argv[1:4]
wanted = {l.strip().lower() for l in open(listing) if l.strip()}
copied = 0
for entry in sorted(os.listdir(src)):
    if entry.lower() not in wanted:
        continue
    s, d = os.path.join(src, entry), os.path.join(dst, entry)
    if os.path.isdir(s):
        shutil.copytree(s, d)
    else:
        shutil.copy2(s, d)
    copied += 1
missing = [w for w in wanted if w not in {e.lower() for e in os.listdir(src)}]
print(f"stage-runtime: copied {copied} entries; {len(missing)} listed names are not in this package version", file=sys.stderr)
for m in sorted(missing):
    print(f"stage-runtime:   not in package: {m}", file=sys.stderr)
PY

# 4. Write the manifest: per-monitor v2 DPI awareness, the supported OS IDs, the marker Reactor looks for, and the
#    registration-free WinRT entries read from the runtime package's own AppxManifest.xml.
python3 -I - "$msix_dir/AppxManifest.xml" "$stage/app.manifest" "$version" <<'PY'
import sys
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

appx, out, version = sys.argv[1:4]
ns = "{http://schemas.microsoft.com/appx/manifest/foundation/windows10}"
root = ET.parse(appx).getroot()
files = {}
for ext in root.iter(ns + "Extension"):
    if ext.get("Category") != "windows.activatableClass.inProcessServer":
        continue
    for server in ext.iter(ns + "InProcessServer"):
        path = server.findtext(ns + "Path")
        for cls in server.iter(ns + "ActivatableClass"):
            files.setdefault(path, {})[cls.get("ActivatableClassId")] = cls.get("ThreadingModel", "both").lower()

lines = [
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
    "<!-- Generated by winui/tools/stage-runtime.sh from the Windows App Runtime " + version + " package. -->",
    '<assembly manifestVersion="1.0" xmlns="urn:schemas-microsoft-com:asm.v1"'
    ' xmlns:winrtv1="urn:schemas-microsoft-com:winrt.v1" xmlns:asmv3="urn:schemas-microsoft-com:asm.v3">',
    '\t<assemblyIdentity version="1.0.0.0" name="LiminalHQ.Quill.WinUISpike" type="win32"/>',
    "\t<description>windows-reactor-self-contained</description>",
    '\t<compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">',
    "\t\t<application>",
    '\t\t\t<supportedOS Id="{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}"/>',
    "\t\t</application>",
    "\t</compatibility>",
    '\t<application xmlns="urn:schemas-microsoft-com:asm.v3">',
    "\t\t<windowsSettings>",
    '\t\t\t<dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true/pm</dpiAware>',
    '\t\t\t<dpiAwareness xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">PerMonitorV2</dpiAwareness>',
    '\t\t\t<longPathAware xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">true</longPathAware>',
    "\t\t</windowsSettings>",
    "\t</application>",
]
for path in sorted(files):
    lines.append("\t<asmv3:file name=%s>" % quoteattr(path))
    for name in sorted(files[path]):
        lines.append("\t\t<winrtv1:activatableClass name=%s threadingModel=%s/>" % (quoteattr(name), quoteattr(files[path][name])))
    lines.append("\t</asmv3:file>")
lines.append("</assembly>")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"stage-runtime: manifest lists {sum(len(v) for v in files.values())} WinRT classes in {len(files)} files", file=sys.stderr)
PY

echo "stage-runtime: $(du -sh "$stage" | cut -f1) staged" >&2
echo "$stage"
